AGREEMENT = (
    b"This is the server agreement.  \r"
    b"The server owner puts any kind of conditions or conditions they want you "
    b"to agree to before entering.  \r"
    b"They can change this agreement by modifying the agreement.txt file in the "
    b"server directory.\r"
    b"Say you agree!"
)


def environment() -> dict:
    """Describe the emulator and the owned working image for the source plan.

    Returns
    -------
    dict
        The environment identity that ``cases.source_plan`` requires.
    """
    return {
        "fixture_profile": "control-only",
        "emulator_pid": 9,
        "emulator_starttime": 10,
        "emulator_sha256": "a" * 64,
        "emulator_netns_inode": 11,
        "owned_working_image": "/ignored/working.dsk",
        "owned_working_image_inode": 12,
    }


def message(  # pylint: disable=too-many-arguments  # ruff: ignore[too-many-arguments]  # the wire header has five fields; callers name the optional error and reply
    kind: int,
    identifier: int,
    values: list[tuple[int, bytes]],
    *,
    error: int = 0,
    reply: int = 1,
) -> bytes:
    """Encode one wire message with the given header and field values.

    Returns
    -------
    bytes
        The raw bytes of the message.
    """
    return bytes.fromhex(
        packet(kind, identifier, payload(values), error=error, reply=reply)
    )


def roster_record(uid: int, name: bytes) -> bytes:
    """Encode one user roster record for the observer's roster reply.

    Returns
    -------
    bytes
        The roster record, with its name length.
    """
    return uid.to_bytes(2, "big") + b"\0\1\0\x20" + len(name).to_bytes(2, "big") + name


class FakeConsumer(control.Timeline):
    """Consume actual generated bytes through socket pairs; no native socket."""

    def __init__(  # pylint: disable=too-many-arguments  # ruff: ignore[too-many-arguments]  # each keyword is one independent fault control of the fake
        self,
        plan: dict,
        *,
        early_b: bool = False,
        wrong_b_id: bool = False,
        b_error: bool = False,
        f_success: bool = False,
        a_eof: bool = False,
    ) -> None:
        """Start a timeline for the plan with the requested fault controls."""
        super().__init__(plan, time.monotonic() + 3)
        self.peers: dict[str, socket.socket] = {}
        self.early_b = early_b
        self.wrong_b_id = wrong_b_id
        self.b_error = b_error
        self.f_success = f_success
        self.a_eof = a_eof

    def connect(self, name: str) -> None:
        """Open a socket pair for ``name`` and complete the hello exchange."""
        client, server = socket.socketpair()
        self.recorder.sockets[name] = client
        self.peers[name] = server
        self.recorder.event(self.action(), name, "connect")
        server.sendall(bytes.fromhex(cases.HELLO_REPLY))
        self.execute({"op": "send", "connection": name, "hex": cases.HELLO})
        self.assert_bytes(server, bytes.fromhex(cases.HELLO))
        self.execute({
            "op": "read",
            "connection": name,
            "size": 8,
            "expect_hex": cases.HELLO_REPLY,
        })
        self.buffers[name] = bytearray()

    @staticmethod
    def assert_bytes(server: socket.socket, expected: bytes) -> None:
        """Require that the peer receives exactly the expected bytes.

        Raises
        ------
        AssertionError
            If the received bytes differ from the expected bytes.
        """
        actual = server.recv(len(expected))
        if actual != expected:
            raise AssertionError(  # ruff: ignore[raise-vanilla-args]  # the message is the fake's fixed diagnostic, kept verbatim
                "Generated request bytes changed"
            )

    def send(self, name: str, raw_hex: str) -> None:
        """Deliver a generated request and answer it with the scripted replies."""
        super().send(name, raw_hex)
        raw = bytes.fromhex(raw_hex)
        self.assert_bytes(self.peers[name], raw)
        if name == "a" and self.a_eof:
            self.peers[name].shutdown(socket.SHUT_WR)
            self.poll(0.002)
        data_size = int.from_bytes(raw[FRAME_SIZE_START:FRAME_HEADER_BYTES], "big")
        if len(raw) < FRAME_HEADER_BYTES or len(raw) != FRAME_HEADER_BYTES + data_size:
            return  # A header and B body remain incomplete; no logical reply.
        frame = decode_frame(raw)
        if name == "o" and frame["type"] == TYPE_LOGIN:
            self.peers[name].sendall(
                message(0, 1, [(160, b"\0\xbe"), (161, b"\0\0")])
                + message(354, 2, [(110, bytes(8))], reply=0)
                + message(109, 3, [(101, AGREEMENT)], reply=0)
            )
        elif name == "b" and frame["type"] == TYPE_LOGIN:
            self.peers[name].sendall(
                message(
                    0, 99 if self.wrong_b_id else 1, [], error=1 if self.b_error else 0
                )
                + message(109, 2, [(101, AGREEMENT)], reply=0)
                + (message(354, 3, [(110, bytes(8))], reply=0) if self.early_b else b"")
            )
        elif name == "f" and frame["type"] == TYPE_LOGIN:
            self.peers[name].sendall(
                message(
                    0,
                    1,
                    [] if self.f_success else [(100, b"Incorrect login.")],
                    error=0 if self.f_success else 1,
                )
            )
        elif name == "o" and frame["type"] == TYPE_GET_USER_ROSTER:
            self.peers[name].sendall(
                message(0, 10, [(300, roster_record(1, b"TimerObserver"))])
            )
        elif name == "o" and frame["type"] == TYPE_EMPTY_ACK:
            self.peers[name].sendall(message(0, frame["id"], []))
        self.poll(0.002)

    def close(self, name: str) -> None:
        """Close the timeline's socket for ``name`` and its fake peer."""
        super().close(name)
        self.peers.pop(name).close()

    def dispose(self) -> None:
        """Close every connection that the timeline has opened."""
        for name in list(self.recorder.sockets):
            self.close(name)
