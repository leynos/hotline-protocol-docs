AGREEMENT = (
    b"This is the server agreement.  \r"
    b"The server owner puts any kind of conditions or conditions they want you to agree to before entering.  \r"
    b"They can change this agreement by modifying the agreement.txt file in the server directory.\r"
    b"Say you agree!"
)


def environment() -> dict:
    return {
        "fixture_profile": "control-only",
        "emulator_pid": 9,
        "emulator_starttime": 10,
        "emulator_sha256": "a" * 64,
        "emulator_netns_inode": 11,
        "owned_working_image": "/ignored/working.dsk",
        "owned_working_image_inode": 12,
    }


def message(
    kind: int,
    identifier: int,
    values: list[tuple[int, bytes]],
    *,
    error: int = 0,
    reply: int = 1,
) -> bytes:
    return bytes.fromhex(
        packet(kind, identifier, payload(values), error=error, reply=reply)
    )


def roster_record(uid: int, name: bytes) -> bytes:
    return uid.to_bytes(2, "big") + b"\0\1\0\x20" + len(name).to_bytes(2, "big") + name


class FakeConsumer(control.Timeline):
    """Consume actual generated bytes through socket pairs; no native socket."""

    def __init__(
        self,
        plan: dict,
        *,
        early_b: bool = False,
        wrong_b_id: bool = False,
        b_error: bool = False,
        f_success: bool = False,
    ) -> None:
        super().__init__(plan, time.monotonic() + 3)
        self.peers: dict[str, socket.socket] = {}
        self.early_b = early_b
        self.wrong_b_id = wrong_b_id
        self.b_error = b_error
        self.f_success = f_success

    def connect(self, name: str) -> None:
        client, server = socket.socketpair()
        self.recorder.sockets[name] = client
        self.peers[name] = server
        self.recorder.event(self.action(), name, "connect")
        server.sendall(bytes.fromhex(cases.HELLO_REPLY))
        self.execute({"op": "send", "connection": name, "hex": cases.HELLO})
        self.assert_bytes(server, bytes.fromhex(cases.HELLO))
        self.execute(
            {
                "op": "read",
                "connection": name,
                "size": 8,
                "expect_hex": cases.HELLO_REPLY,
            }
        )
        self.buffers[name] = bytearray()

    @staticmethod
    def assert_bytes(server: socket.socket, expected: bytes) -> None:
        actual = server.recv(len(expected))
        if actual != expected:
            raise AssertionError("Generated request bytes changed")

    def send(self, name: str, raw_hex: str) -> None:
        super().send(name, raw_hex)
        raw = bytes.fromhex(raw_hex)
        self.assert_bytes(self.peers[name], raw)
        if len(raw) < 20 or len(raw) != 20 + int.from_bytes(raw[16:20], "big"):
            return  # A header and B body remain incomplete; no logical reply.
        frame = decode_frame(raw)
        if name == "o" and frame["type"] == 107:
            self.peers[name].sendall(
                message(0, 1, [(160, b"\0\xbe"), (161, b"\0\0")])
                + message(354, 2, [(110, bytes(8))], reply=0)
                + message(109, 3, [(101, AGREEMENT)], reply=0)
            )
        elif name == "b" and frame["type"] == 107:
            self.peers[name].sendall(
                message(
                    0, 99 if self.wrong_b_id else 1, [], error=1 if self.b_error else 0
                )
                + message(109, 2, [(101, AGREEMENT)], reply=0)
                + (message(354, 3, [(110, bytes(8))], reply=0) if self.early_b else b"")
            )
        elif name == "f" and frame["type"] == 107:
            self.peers[name].sendall(
                message(
                    0,
                    1,
                    [] if self.f_success else [(100, b"Incorrect login.")],
                    error=0 if self.f_success else 1,
                )
            )
        elif name == "o" and frame["type"] == 300:
            self.peers[name].sendall(
                message(0, 10, [(300, roster_record(1, b"TimerObserver"))])
            )
        elif name == "o" and frame["type"] == 500:
            self.peers[name].sendall(message(0, frame["id"], []))
        self.poll(0.002)

    def close(self, name: str) -> None:
        super().close(name)
        self.peers.pop(name).close()

    def dispose(self) -> None:
        for name in list(self.recorder.sockets):
            self.close(name)


class LivenessTests(unittest.TestCase):
    def plan(self) -> dict:
        return cases.source_plan(environment())

    def exercise(self, **faults) -> FakeConsumer:
        plan = self.plan()
        fake = FakeConsumer(plan, **faults)
        self.addCleanup(fake.dispose)
        fake.connect("o")
        fake.send("o", plan["observer_login_hex"])
        control.check_observer(fake)
        fake.operations.append({"label": "t0", "elapsed_ns": 0})
        for op in plan["schedule"]["operations"]:
            event_start, frame_start = len(fake.recorder.events), len(fake.frames)
            control.perform_operation(fake, op, time.monotonic() + 2)
            fake.operations.append(
                {
                    "label": op["label"],
                    "event_range": [event_start, len(fake.recorder.events)],
                    "frame_range": [frame_start, len(fake.frames)],
                }
            )
        fake.window_status = {
            name: fake.terminals.get(name, "bounded_no_eof_through_window")
            for name in fake.buffers
        }
        fake.window_frame_count = len(fake.frames)
        return fake

    def report(self, fake: FakeConsumer) -> dict:
        plan = fake.plan
        return {
            "status": "completed",
            "window_completed": True,
            "window_frame_count": fake.window_frame_count,
            "native_conformance": False,
            "plan_sha256": control.digest((json.dumps(plan, indent=2) + "\n").encode()),
            "cases_sha256": control.digest(Path(cases.__file__).read_bytes()),
            "source_sha256": control.digest(Path(control.__file__).read_bytes()),
            "oracle_sha256": control.ORACLE_SHA256,
            "events": deepcopy(fake.recorder.events),
            "frames": deepcopy(fake.frames),
            "operations": deepcopy(fake.operations),
            "streams": fake.recorder.streams(),
            "unparsed_hex": {name: raw.hex() for name, raw in fake.buffers.items()},
            "window_status": dict(fake.window_status),
        }

    def test_generated_schedule_through_fake_consumer(self) -> None:
        fake = self.exercise()
        control.check_complete(fake)
        plan = fake.plan
        self.assertEqual(len(fake.buffers), 7)
        self.assertEqual(
            len(
                [
                    op
                    for op in plan["schedule"]["operations"]
                    if op["label"].startswith("o500")
                ]
            ),
            26,
        )
        self.assertEqual(
            [
                (op["label"], op["at_seconds"])
                for op in plan["schedule"]["operations"]
                if op["label"].startswith("b")
            ],
            [
                ("b-admit-preonline", 0),
                ("b107-selected", 45),
                ("b121-partial-body", 50),
            ],
        )
        self.assertEqual(
            len(
                bytes.fromhex(
                    next(
                        op["hex"]
                        for op in plan["schedule"]["operations"]
                        if op["label"] == "b121-partial-body"
                    )
                )
            ),
            21,
        )
        self.assertEqual(fake.window_status["b"], "bounded_no_eof_through_window")

    def test_premature_b_online_blocks_partial121(self) -> None:
        with self.assertRaisesRegex(ValueError, "became online"):
            self.exercise(early_b=True)

    def test_wrong_b_reply_id_blocks_partial121(self) -> None:
        with self.assertRaisesRegex(ValueError, "valid107"):
            self.exercise(wrong_b_id=True)

    def test_b_nonzero_status_blocks_partial121(self) -> None:
        with self.assertRaisesRegex(ValueError, "valid107"):
            self.exercise(b_error=True)

    def test_failed_login_must_remain_failure(self) -> None:
        fake = self.exercise(f_success=True)
        with self.assertRaisesRegex(ValueError, "F failure107"):
            control.check_complete(fake)

    def test_observer_roster_must_exclude_b(self) -> None:
        fake = self.exercise()
        matching = control.matching(fake.frames, "o", 10)[0]
        matching["fields"].append(
            {"id": 300, "hex": roster_record(2, cases.NAME_B).hex()}
        )
        with self.assertRaisesRegex(ValueError, "B appeared"):
            control.check_b_preonline(fake)

    def test_missing_window_classification_rejected(self) -> None:
        fake = self.exercise()
        fake.window_status.pop("a")
        with self.assertRaisesRegex(ValueError, "Missing window observation"):
            control.check_complete(fake)

    def test_truncated_receive_bytes_retained(self) -> None:
        plan = self.plan()
        timeline = control.Timeline(plan, time.monotonic() + 1)
        client, peer = socket.socketpair()
        self.addCleanup(client.close)
        self.addCleanup(peer.close)
        timeline.recorder.sockets["a"] = client
        timeline.buffers["a"] = bytearray()
        prefix = bytes.fromhex(packet(0, 3, payload([]), reply=1))[:11]
        peer.sendall(prefix)
        timeline.poll(0.02)
        self.assertEqual(timeline.buffers["a"], prefix)
        self.assertEqual(timeline.frames, [])
        self.assertEqual(timeline.recorder.streams()["a"]["received_hex"], prefix.hex())

    def test_source_hash_and_environment_drift(self) -> None:
        with self.assertRaisesRegex(ValueError, "identity incomplete"):
            cases.source_plan({"fixture_profile": "control-only"})
        with self.assertRaisesRegex(ValueError, "reserved"):
            cases.source_plan(environment(), 15841)
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "plan"
            cases.write_plan(path, environment())
            self.assertEqual(control.prepared(path), self.plan())
            altered = json.loads((path / "plan.json").read_text())
            altered["schedule"]["operations"][0]["hex"] = "00"
            (path / "plan.json").write_text(json.dumps(altered))
            with self.assertRaisesRegex(ValueError, "hash differs"):
                control.prepared(path)

    def test_unmeasured_close_not_required(self) -> None:
        fake = self.exercise()
        control.check_complete(fake)
        self.assertFalse(any(value == "eof" for value in fake.window_status.values()))

    def test_late_tail_kept_outside_window_inference(self) -> None:
        fake = self.exercise()
        raw = message(0, 2, [])
        fake.frames.append(
            {"connection": "b", "raw_hex": raw.hex(), **decode_frame(raw)}
        )
        control.check_complete(fake)
        fake.window_frame_count = len(fake.frames)
        with self.assertRaisesRegex(ValueError, "Incomplete B121"):
            control.check_complete(fake)

    def test_offline_report_source_raw_and_delivery_faults(self) -> None:
        fake = self.exercise()
        source = self.report(fake)
        control.verify_report(fake.plan, source)
        for key, value, reason in (
            ("source_sha256", "0" * 64, "source identity"),
            ("plan_sha256", "0" * 64, "source identity"),
            ("window_status", {}, "finite socket status"),
        ):
            with self.subTest(key=key):
                altered = deepcopy(source)
                altered[key] = value
                with self.assertRaisesRegex(ValueError, reason):
                    control.verify_report(fake.plan, altered)
        altered = deepcopy(source)
        altered["streams"]["b"]["sent_hex"] += "00"
        with self.assertRaisesRegex(ValueError, "Raw streams"):
            control.verify_report(fake.plan, altered)
        altered = deepcopy(source)
        altered["frames"][0]["id"] = 999
        with self.assertRaisesRegex(ValueError, "Decoded frame"):
            control.verify_report(fake.plan, altered)


if __name__ == "__main__":
    unittest.main()
